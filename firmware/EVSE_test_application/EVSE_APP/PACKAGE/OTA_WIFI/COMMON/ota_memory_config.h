#ifndef EVSE_APP_COMMON__OTA_MEMORY_CONFIG_H
#define EVSE_APP_COMMON__OTA_MEMORY_CONFIG_H

#include <stdint.h>

/*
 * STM32F429ZI Internal Flash
 *
 * 0x08000000 ~ 0x081FFFFF
 */
#define OTA_FLASH_START_ADDRESS       0x08000000UL
#define OTA_FLASH_END_ADDRESS         0x08200000UL

/*
 * Bootloader
 *
 * 0x08000000 ~ 0x0801FFFF
 */
#define OTA_BOOTLOADER_START_ADDRESS  0x08000000UL
#define OTA_BOOTLOADER_END_ADDRESS    0x08020000UL

/*
 * Running Application
 *
 * 0x08020000 ~ 0x080FFFFF
 *
 * Capacity = 0x000E0000 = 896 KiB
 */
#define OTA_APPLICATION_START_ADDRESS 0x08020000UL
#define OTA_APPLICATION_END_ADDRESS   0x08100000UL

#define OTA_APPLICATION_CAPACITY      (OTA_APPLICATION_END_ADDRESS - OTA_APPLICATION_START_ADDRESS)

/*
 * OTA Staging
 *
 * 0x08100000 ~ 0x081DFFFF
 *
 * Capacity = 896 KiB
 */
#define OTA_STAGING_START_ADDRESS     0x08100000UL
#define OTA_STAGING_END_ADDRESS       0x081E0000UL

#define OTA_STAGING_CAPACITY          (OTA_STAGING_END_ADDRESS - OTA_STAGING_START_ADDRESS)

/*
 * Reserved
 *
 * 추후 manifest / rollback metadata 등의 확장 영역.
 */
#define OTA_RESERVED_START_ADDRESS    0x081E0000UL
#define OTA_RESERVED_END_ADDRESS      0x08200000UL

/*
 * STM32F429ZI RAM ranges.
 *
 * Staging image Vector Table 검증에 사용합니다.
 */
#define OTA_SRAM_START_ADDRESS        0x20000000UL
#define OTA_SRAM_END_ADDRESS          0x20030000UL

#define OTA_CCMRAM_START_ADDRESS      0x10000000UL
#define OTA_CCMRAM_END_ADDRESS        0x10010000UL

#define OTA_VECTOR_TABLE_MIN_SIZE     8U

#endif